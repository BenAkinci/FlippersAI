import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL(`./${p}`,import.meta.url),'utf8')
const expect=(v,m)=>{if(!v)throw new Error(m)}
const manifest=JSON.parse(read('manifest.json'))
const scout=read('scout-controller-v090.js')
const overlay=read('scout-rating-overlay.js')
const compact=overlay.replace(/\s+/g,'')
const [maj,min]=String(manifest.version||'0.0.0').split('.').map(Number)
expect(maj>0||(maj===0&&min>=90),'manifest must package v0.90.2-compatible or newer Scout polish')
expect(scout.includes('document.body.dataset.v088WorkingIds=JSON.stringify(workingIds)'),'Working IDs must be published to the bucket UI')
expect(scout.includes("document.body.dataset.v088WorkingIds='[]'"),'new scan must clear old Working IDs')
expect(scout.includes("toast('Starting a new Scout…');await handleScan()"),'Start new scan must immediately scan the current marketplace page')
expect(!scout.includes("await clearPersisted();location.reload()"),'Start new scan must not return to the default/home view')
expect(compact.includes('BADGE+')&&compact.includes('tone(rating)'),'rating paint must compute badge state from the current rating')
expect(/if\(badge\.className!==[^)]+\)badge\.className=/.test(compact),'rating class must only mutate when changed')
expect(/if\(badge\.innerHTML!==[^)]+\)badge\.innerHTML=/.test(compact),'rating contents must only mutate when changed')
expect(/if\(badge\.title!==[^)]+\)badge\.title=/.test(compact),'rating title must only mutate when changed')
expect(compact.includes('classList.contains(IMAGE)')&&compact.includes('classList.contains(t)'),'rated image classes must only change when needed')
expect(/function schedule\(delay\s*=\s*\d+\)/.test(overlay),'marketplace repaint scheduling must remain present')
console.log('v0.90.2 Working + stable overlay + immediate new scan contract passed')

import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL(`./${p}`,import.meta.url),'utf8')
const expect=(v,m)=>{if(!v)throw new Error(m)}
const manifest=JSON.parse(read('manifest.json'))
const api=read('api.js')
const session=read('scout-session-v070.js')
const orch=read('scout-orchestrator-v080.js')
const side=read('sidepanel.html')
const work=read('workspace.html')
const enrich=read('scout-enrichment-state-v089.js')
const details=read('scout-card-details.js')
const actions=read('scout-actions-v087.js')
const buckets=read('scout-buckets-v088.js')
const css=read('scout-v080.css')
const parts=String(manifest.version||'').split('.').map(Number)
expect(parts[0]===0&&parts[1]===89&&parts[2]>=12,'manifest must preserve v0.89.12+ Scout stability line')
expect(api.includes('SCOUT_CACHE_TTL_MS = 5000'),'Scout read cache must have a stable short TTL')
expect(api.includes("const session = params.get('session_id')"),'Scout cache must canonicalise session reads')
expect(api.includes("return table + '?select=*&session_id=' + session"),'equivalent full session reads must share one cache key')
for(const html of [side,work]){
  expect(!html.includes('scout-start-watchdog-v081.js'),'legacy Scout watchdog must not load')
  expect((html.match(/scout-loader-state-v083\.js/g)||[]).length<=1,'loader-state script must not load twice')
}
expect(!enrich.includes('setInterval(()=>schedule(0),1800)'),'enrichment UI must not poll Supabase continuously')
expect(!details.includes('new MutationObserver'),'card details must refresh from Scout events, not arbitrary DOM churn')
expect(!actions.includes('new MutationObserver'),'Scout actions must refresh from Scout events, not arbitrary DOM churn')
expect(!buckets.includes('new MutationObserver'),'Scout buckets must refresh from Scout events, not arbitrary DOM churn')
expect(session.includes('STALE_SCOUT_MS=5*60*1000'),'restored Scout must have a stale-session threshold')
expect(session.includes('interrupted:true'),'stale restored Scout must persist interrupted state')
expect(session.includes('Previous Scout interrupted'),'stale Scout UI must be explicit')
expect(orch.includes('interrupted:false'),'orchestrator must own interrupted runtime state')
expect(orch.includes("O.interrupted?'Resume Scout'"),'interrupted Scout must offer Resume')
expect(orch.includes("O.interrupted?'Discard Scout'"),'interrupted Scout must offer Discard')
expect(orch.includes('if(O.busy||O.paused||O.stopped||O.interrupted)return'),'interrupted Scout must never auto-run rating')
expect(orch.includes("if(!O.interrupted)queueEnrichment"),'interrupted Scout must not auto-run enrichment')
expect(css.includes('#v080Loading.interrupted .scout-loading-spinner'),'interrupted Scout must not show an active spinner')
console.log('v0.89.12 Scout lifecycle + egress stability contract passed')
